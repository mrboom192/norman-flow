const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

// Called by Metro for start, export and cloud builds; never require missing files.
function prepareBaseData(root = path.resolve(__dirname, "..")) {
  const folder = path.join(root, "assets/data/base");
  const names = fs.existsSync(folder)
    ? fs
        .readdirSync(folder)
        .filter(
          (name) =>
            /\.(geojson|kmz|kml|xlsx|xls|csv)$/i.test(name) && !name.startsWith("~$"),
        )
        .sort()
    : [];
  const entries = names
    .map((name) => {
      if (!fs.statSync(path.join(folder, name)).isFile()) return null;
      const version = crypto
        .createHash("sha256")
        .update(fs.readFileSync(path.join(folder, name)))
        .digest("hex");
      return `  { name: ${JSON.stringify(name)}, version: ${JSON.stringify(version)}, module: require(${JSON.stringify(`../../assets/data/base/${name}`)}) },`;
    })
    .filter(Boolean);
  const output =
    "// Generated by scripts/prepare-base-data.cjs. Do not edit.\n/* eslint-disable @typescript-eslint/no-require-imports -- Metro needs literal asset references. */\nexport const baseAssets: { name: string; version: string; module: number }[] = [\n" +
    entries.join("\n") +
    "\n];\n";
  const target = path.join(root, "src/services/base-assets.generated.ts");
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output)
    fs.writeFileSync(target, output);
  return names;
}
module.exports = { prepareBaseData };
if (require.main === module) prepareBaseData();
